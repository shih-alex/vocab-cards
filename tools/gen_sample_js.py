"""Regenerate sample.js from the sample deck text file.

    python tools/gen_sample_js.py [path/to/deck.txt]

Default source: samples/範例_高中常用單字.txt
Output:         sample.js  ->  window.VC_SAMPLE = { name: "...", text: "..." };

The deck name is taken from the first `#deck:` line (falls back to the file
name). The output is pure ASCII (non-ASCII is \\u-escaped), so it loads
correctly no matter how the page or server declares its encoding, and it is
safe to inline inside a <script> element.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT / "samples" / "範例_高中常用單字.txt"
OUTPUT = ROOT / "sample.js"

# Same directive syntax the app's parser accepts: "#deck:", "# deck:", full-width colon, any case.
DECK_RE = re.compile(r"^#\s*deck\s*[:：]\s*(.*?)\s*$", re.IGNORECASE)


def js_string(s: str) -> str:
    """JSON string literal that is also safe inside an inline <script>."""
    return json.dumps(s, ensure_ascii=True).replace("</", "<\\/")


def main() -> int:
    source = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else DEFAULT_SOURCE
    if not source.is_file():
        print(f"error: sample file not found: {source}", file=sys.stderr)
        return 1

    text = source.read_text(encoding="utf-8-sig").replace("\r\n", "\n").replace("\r", "\n")

    name = source.stem
    for line in text.split("\n"):
        m = DECK_RE.match(line.strip())
        if m and m.group(1):
            name = m.group(1)
            break

    js = (
        "// Generated by tools/gen_sample_js.py from the deck in samples/ - do not edit by hand.\n"
        "window.VC_SAMPLE = {\n"
        f"  name: {js_string(name)},\n"
        f"  text: {js_string(text)}\n"
        "};\n"
    )
    OUTPUT.write_text(js, encoding="utf-8", newline="\n")

    cards = sum(1 for ln in text.split("\n") if ln.strip() and not ln.lstrip().startswith("#"))
    sys.stdout.reconfigure(errors="replace")
    print(f"wrote {OUTPUT.name}: {cards} card lines, {OUTPUT.stat().st_size / 1024:.1f} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
